/** 钥匙空着（新建时必填；改了地址时也是必填，见 `NEED_KEY`）。 */
export const KEY_REQUIRED = '钥匙不能为空'
/** 别名空着。用户看到的是别名，所以这句要像句人话，不是"字段不能为空"。 */

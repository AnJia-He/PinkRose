import {
  Images, MessagesSquare, Palette, SlidersHorizontal, UserRound, WandSparkles,
} from 'lucide-react'
import type { View } from './view'

/**
 * 左栏。**详情页时「作品」也是亮的** —— 详情页属于作品那一支，不是第三个地方。
 *
 * ★ 2026-10-01（Task 6，§6.1）：三支 = **修图 / 对话 / 作品**，顺序就是这个
 * —— 修图是主入口，作品在最后。三样是三件事：现在是「修图」（这次在改的照片）、
 * 「对话」是过程（改过哪些），「作品」是结果。别合并。
 *
 * ★ 2026-10-04：**「调色」搬进来成了第四支**，插在「修图」后面（用户要的，
 * 见下面那颗按钮上的注释）。四支仍然是一句话说得清的一列：
 * **这张照片（修图 / 调色）、改过的那些（对话）、存下来的那些（作品）**。
 * 前两支是同一样东西的两种改法，所以挨着。
 * ⚠️ 别因为"调色只是修图页底下一条面板"就把它塞回顶栏 —— 那正是它搬家的原因。
 *
 * ★ 2026-10-03：**下面还钉着两颗**，和上面三支隔着一整片空白（`.nav-home`
 * 那条 auto 外边距）—— 隔开是**有意的**，它们是另一个层次的东西：
 *   · 「产品介绍」 —— **出门**（回门面），见下面那段；
 *   · 「个人设置」 —— 用户管理那一页（§3.6），**从顶栏右上角那颗 👤 搬来的**。
 *     用户原话：「**这个一行都不要，个人设置放到首页下面**」—— 那一行（顶栏）
 *     连品牌名一起撤了，👤 落在这一列的最底下。搬过来还顺手治好一个旧毛病：
 *     👤 原来只住在顶栏，而顶栏**只有修图页有** —— 站在作品页/对话页的人
 *     根本进不去设置，得先绕回修图页。
 *
 * ★★ 2026-10-08（用户原话：「给导航栏设计相关的图标组件」）：**五支各配一个图标**
 * —— 图标在左、文字在右（`.nav-item` 是 flex 行，见 `styles.css` 那条注释）。
 * 选型的规矩三条，加新图标时照这个来：
 *   · **一个图标认一件事**，五支摆在 92px 的一列里、必须一眼分得开：
 *     修图 = `WandSparkles`（说话改图 = 魔法棒，和"手动拖滑块"的调色分开）、
 *     调色 = `Palette`（调色盘）、Lut = `SlidersHorizontal`、对话 = `MessagesSquare`、
 *     作品 = `Images`。
 *   · ★ **同一个概念全站同一个图标**：Lut 用的滑杆就是对话区加号里那一项用的
 *     那个（`ChatPanel` 的 `.chat-tool`）—— 同一样东西在两处长得一样，用户不用
 *     重新认一遍。
 *   · **尺寸 16、线宽 1.5**（尺子守卫钉着：每个 lucide 图标必须显式写
 *     `strokeWidth={1.5}`，lucide 默认是 2，不写就是静默变粗）。
 * ⚠️ 图标是**装饰**：`aria-hidden` 必写 —— 名字是旁边那两个字，读屏和
 *   "按文字找按钮"的测试（`goNav` / 左栏那份清单）都不该被 svg 搅到。
 * ⚠️ **窄屏那一行上图标全部藏起来**（`.nav-item:not(.nav-me) > svg`）——
 *   390px 的一行放不下"图标 + 文字"七颗，撑出横向滚动条；理由在 CSS 那条里。
 * ⚠️ 下面两颗**不配图标**：它们是"另一个层次"（出门 / 设置），这一列用
 *   一整片空白把它们和五支隔开就是这个意思 —— 配上图标反而混成一列。
 */
export function Nav({ view, onGo }: { view: View; onGo: (v: View) => void }) {
  // ⚠️ 这一列**不随"手上有没有照片"变**，是用户 2026-10-04 亲口定的：
  //   「**调色要一直在导航栏**，没有图片的时候显示图片的地方提示还没有照片不就好了？
  //    但是微调的按钮要一直在」。
  //
  //   在那之前我做过一版"没有照片时把那一格藏起来"，理由写得挺像回事
  //   （"关于这张照片的工具，照片在才有"，照的是顶栏那三颗的规矩）—— 想窄了：
  //   **顶栏那三颗是"对这张照片做什么"，而左栏这一列是"这里有哪几件事"。**
  //   一件事在不在，不该随手上有没有照片变；**该换的是"没东西可看"那块地方**
  //   （那件事在 `App.tsx` 里：没照片时照片那块地方说一句「还没有照片」，
  //    见 `ui/AdjustEmpty.tsx`）。
  const here = view.kind === 'work' ? 'gallery' : view.kind
  /** 站在用户管理那两页（账号 / 模型设置）时，「个人设置」是亮的 ——
   *  模型设置是它底下一格（§7.4），不是第五个地方。 */
  const atAccount = view.kind === 'account' || view.kind === 'models'
  return (
    <nav className="nav">
      <button className={`nav-item${here === 'edit' ? ' on' : ''}`}
              onClick={() => onGo({ kind: 'edit' })}>
        <WandSparkles size={16} strokeWidth={1.5} aria-hidden="true" />
        修图
      </button>
      {/* ★ 2026-10-04：**「调色」从顶栏搬进来了**（用户原话：「那个微调照片的
          放在导航栏单列出来」——他叫的「微调」是 09-30 改名前的旧词，同一件事）。

          在那之前它是顶栏里的一颗开关按钮，和「下载 / 保存 / 新的一张」挤一排。
          搬家的理由不止"用户说了"：那三颗是**把图拿走**，这一颗是**改这张图** ——
          而那三颗只在有照片的那一刻才有意义，于是它跟着一起，照片一撤就整条消失，
          调色这件事在界面上**没有名字**。

          ⚠️ 紧挨着「修图」、**不是**挪到「作品」后面：这两支说的是同一张照片
          （修图 = 说话改、调色 = 手动改），另外两支说的是别的照片
          （对话 = 改过的那些、作品 = 存下来的那些）。

          ⚠️ **它一直在 —— 别再加"没有照片就不显示"那道判断**（2026-10-04 试过，
          被用户当场否掉：「微调的按钮要**一直在**」）。没有照片时该变的是**照片那块
          地方**（`ui/AdjustEmpty.tsx` 那句「还没有照片。」），不是这一格。*/}
      <button className={`nav-item${here === 'adjust' ? ' on' : ''}`}
              onClick={() => onGo({ kind: 'adjust' })}>
        <Palette size={16} strokeWidth={1.5} aria-hidden="true" />
        调色
      </button>
      {/* ★ 2026-10-05：**「滤镜」也进了这一列**（用户：「把滤镜导入放到导航里吧，
          然后我没看到怎么去调用 lut 文件」）。

          在那之前这一页几乎**没有入口**：调色面板里"一个滤镜都没有"时那颗
          「去导入」（用过一次就消失了），外加「个人设置」里有一行 —— 而那是
          **管理**，不是"我要去用它"。用户找不到，就是这条路太深。

          ⚠️ 位置紧挨着「调色」（不是挪到「作品」旁边）：导入/管理滤镜是**为这张
          照片**做的事，和修图/调色同一组；后面那两支说的是别的照片。
          ⚠️ 它和「调色」不一样，**没有照片也能进** —— 那一页是管理自己的滤镜库，
          和手上有没有照片无关。 */}
      <button className={`nav-item${here === 'luts' ? ' on' : ''}`}
              onClick={() => onGo({ kind: 'luts' })}>
        <SlidersHorizontal size={16} strokeWidth={1.5} aria-hidden="true" />
        Lut
      </button>
      <button className={`nav-item${here === 'sessions' ? ' on' : ''}`}
              onClick={() => onGo({ kind: 'sessions' })}>
        <MessagesSquare size={16} strokeWidth={1.5} aria-hidden="true" />
        对话
      </button>
      <button className={`nav-item${here === 'gallery' ? ' on' : ''}`}
              onClick={() => onGo({ kind: 'gallery' })}>
        <Images size={16} strokeWidth={1.5} aria-hidden="true" />
        作品
      </button>
      {/* ★ 2026-10-03：**回门面**（用户要的："能从操作页回到落地页"）。
          上一版里这件事**做不到** —— `/` 是落地页，而登录着的人一打开 `/` 就被
          送去 `/app`（见 App.tsx 那条自动跳转），自己人被关在 App 里出不去。

          ⚠️ 它**不是第四支导航**：上面那三支是 App 里的三个地方，这一颗是
          **出门**（去门面）。所以它钉在最底下、和上面隔着一整片空白
          （`.nav-home` 那条规则），别顺手挪到三支中间去。
          走的是 `ui/view.ts` 的 `FRONT_PAGE`（`/?home=1`）—— 那个参数就是
          "这一趟是特意来的"，自动跳转认得出它。

          ★ 2026-10-04：**这几个字是用户自己改的** —— 原来写的是「首页」。他先问
          了"这个名字在哪个文件"，然后自己把这一行改成了「产品介绍」。改得有道理：
          它出门去的是**营销页**，"产品介绍"比"首页"准（"首页"听着像 App 自己的
          家 —— 而那是 `/app`，不是这一页）。
          ⚠️ 这两个字**不止这一处认它**：`App.test.tsx` 里那条左栏清单和两句
          `goNav(...)` 是**按文字**找它的，改了这里就得跟着改（版面探针按
          `.nav-home` 这个类找它，不受影响）。 */}
      <button className="nav-item nav-home"
              onClick={() => onGo({ kind: 'landing' })}>产品介绍</button>
      {/* 用户管理（§3.6）—— 2026-10-03 从顶栏那颗 👤 搬下来的，就在「产品介绍」下面
          （用户指定的位置）。它排在 `.nav-home` **后面**，所以跟着一起被那条
          auto 外边距推到底 —— 这两颗是一组"和上面三支不一样的东西"。

          ★ 2026-10-04：**文字换成人物图标**（用户原话：「个人设置改为人物图标」）。
          它本来就是那颗 👤 搬下来的，换句话说这是**搬回它原来的长相** ——
          左栏里另外五颗都是"去哪儿"（修图 / 调色 / 对话 / 作品 / 产品介绍），
          只有这一颗是"**我**"，所以它用一个人物图标反而更好认。

          ⚠️ 因为没有可见文字了，**那两行标记就不是可选项**：
            · `aria-label` —— 读屏和"按标签找元素"的测试都靠它
              （`App.test.tsx` 的 `openAccount()`、`check:layout` 量的那个名字）；
            · `title` —— 鼠标停上去能看见"个人设置"（图标独自站着时，
              这是唯一能补上名字的地方）。
          删了任何一个，都会变成"看着没问题、但没人找得到它"。*/}
      <button className={`nav-item nav-me${atAccount ? ' on' : ''}`}
              onClick={() => onGo({ kind: 'account' })}
              aria-label="个人设置" title="个人设置">
        <UserRound size={20} strokeWidth={1.5} aria-hidden="true" />
      </button>
    </nav>
  )
}

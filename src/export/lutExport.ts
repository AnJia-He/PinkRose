import type { Adjustments } from '../../shared/adjustments.ts'
import type { Cube } from '../../shared/lut.ts'
import { TonePipeline } from '../render/pipeline'

/** 33³ 是通用 .cube 的常用尺寸；35,937 条，文件约 1.5MB。 */
export const LUT_EXPORT_SIZE = 33

/**
 * LUT 只承载**逐像素颜色变换**。清晰度 / 暗角 / 镜头 / 美颜 / 纹理这些
 * 依赖邻域、坐标或人脸的效果不能进 LUT；导出时显式归零，避免把一帧照片
 * 的局部效果错误地套到所有颜色上。
 */
export function colorOnlyAdjustments(a: Adjustments): Adjustments {
  return {
    ...a,
    clarity: 0,
    vignette: 0,
    skinSmooth: 0,
    dehaze: 0,
    hdr: 0,
    glow: 0,
    texture: 0,
    sharpen: 0,
    sharpenRadius: 0,
    sharpenMasking: 0,
    noiseReduction: 0,
    colorNoiseReduction: 0,
    grain: 0,
    skinBrighten: 0,
    skinRosy: 0,
    perspectiveV: 0,
    perspectiveH: 0,
    lensBlur: 0,
    lensRange: 0,
    lensFeather: 0,
    lensFocusX: 0,
    lensFocusY: 0,
    lensDistortion: 0,
    lensChromatic: 0,
    lensVignette: 0,
  }
}

/** 生成 33 个蓝色切片的横向图集：一列一块，块内 x = r、y = g。 */
export function buildLutAtlas(size = LUT_EXPORT_SIZE): HTMLCanvasElement {
  const width = size * size
  const height = size
  const canvas = document.createElement('canvas')
  canvas.width = width
  canvas.height = height
  const ctx = canvas.getContext('2d')
  if (!ctx) throw new Error('这台浏览器建不了 LUT 色卡')
  const image = ctx.createImageData(width, height)
  const denom = Math.max(1, size - 1)
  for (let b = 0; b < size; b++) {
    for (let g = 0; g < size; g++) {
      for (let r = 0; r < size; r++) {
        const i = (g * width + b * size + r) * 4
        image.data[i] = Math.round(r / denom * 255)
        image.data[i + 1] = Math.round(g / denom * 255)
        image.data[i + 2] = Math.round(b / denom * 255)
        image.data[i + 3] = 255
      }
    }
  }
  ctx.putImageData(image, 0, 0)
  return canvas
}

export function cubeTextFromLookup(
  size: number,
  lookup: (r: number, g: number, b: number) => [number, number, number],
  title = 'PinkRose look',
): string {
  const safeTitle = title.replace(/[\r\n"]/g, ' ').trim() || 'PinkRose look'
  const lines: string[] = [
    '# Generated by PinkRose',
    `TITLE "${safeTitle}"`,
    `LUT_3D_SIZE ${size}`,
    'DOMAIN_MIN 0.000000 0.000000 0.000000',
    'DOMAIN_MAX 1.000000 1.000000 1.000000',
  ]
  for (let b = 0; b < size; b++) {
    for (let g = 0; g < size; g++) {
      for (let r = 0; r < size; r++) {
        const [rv, gv, bv] = lookup(r, g, b)
        lines.push(
          `${(rv / 255).toFixed(6)} ${(gv / 255).toFixed(6)} ${(bv / 255).toFixed(6)}`,
        )
      }
    }
  }
  return `${lines.join('\n')}\n`
}

/**
 * 把当前调色（以及当前 Lut）烘焙成 3D LUT。
 *
 * 色卡图集交给**现有 shader**，所以顺序、曲线、HSL、分离色调都和画面
 * 完全同源；不是另写一套 CPU 近似。
 */
export async function exportLookCube(
  params: Adjustments,
  cube: Cube | null,
  lutAmount: number,
  title = 'PinkRose look',
  size = LUT_EXPORT_SIZE,
): Promise<string> {
  const atlas = buildLutAtlas(size)
  // ⚠️ 不能拿 `makeCanvas`：它先拿了 2D 上下文，之后再 `getContext('webgl2')`
  // 会返回 null（一张画布只能有一种上下文）。这里必须是干净画布。
  const out = document.createElement('canvas')
  const pipeline = new TonePipeline(out)
  const bitmap = await createImageBitmap(atlas)
  try {
    pipeline.setImage({ bitmap, width: atlas.width, height: atlas.height })
    pipeline.resizeToImage()
    pipeline.setLut(cube)
    pipeline.render(colorOnlyAdjustments(params), lutAmount)
    const raw = pipeline.readPixels()
    // readPixels 是自下而上；翻成自上而下后再按 (b,g,r) 取值。
    const rowBytes = atlas.width * 4
    const top = new Uint8Array(raw.length)
    for (let y = 0; y < atlas.height; y++) {
      const src = (atlas.height - 1 - y) * rowBytes
      top.set(raw.subarray(src, src + rowBytes), y * rowBytes)
    }
    return cubeTextFromLookup(size, (r, g, b) => {
      const i = (g * atlas.width + b * size + r) * 4
      return [top[i]!, top[i + 1]!, top[i + 2]!]
    }, title)
  } finally {
    bitmap.close()
    pipeline.dispose()
  }
}

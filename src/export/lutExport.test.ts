import { describe, expect, it } from 'vitest'
import { ZERO } from '../../shared/adjustments.ts'
import { colorOnlyAdjustments, cubeTextFromLookup } from './lutExport.ts'

describe('LUT 导出', () => {
  it('只保留逐像素颜色参数，空间 / 镜头 / 美颜效果归零', () => {
    const out = colorOnlyAdjustments({
      ...ZERO,
      exposure: 20, saturation: 30, curveMidtones: 10,
      splitHiHue: 32, splitLoHue: 195, splitAmount: 40,
      splitMidHue: 120, splitMidAmount: 25, splitBalance: -20,
      clarity: 40, vignette: 50, skinSmooth: 60, lensDistortion: 30,
      lensBlur: 20, noiseReduction: 10, colorNoiseReduction: 35,
      sharpenRadius: 40, sharpenMasking: 70,
    })
    expect(out).toMatchObject({
      exposure: 20, saturation: 30, curveMidtones: 10,
      splitHiHue: 32, splitLoHue: 195, splitAmount: 40,
      splitMidHue: 120, splitMidAmount: 25, splitBalance: -20,
      clarity: 0, vignette: 0, skinSmooth: 0, lensDistortion: 0,
      lensBlur: 0, noiseReduction: 0, colorNoiseReduction: 0,
      sharpenRadius: 0, sharpenMasking: 0,
    })
  })

  it('按标准 .cube 输出：尺寸、domain、红最快 / 蓝最慢', () => {
    const lookup = (r: number, g: number, b: number): [number, number, number] =>
      [r * 255, g * 255, b * 255]
    const text = cubeTextFromLookup(2, lookup, 'Test "Look"')
    const lines = text.trim().split('\n')
    expect(lines[0]).toBe('# Generated by PinkRose')
    expect(lines[1]).toBe('TITLE "Test  Look"')
    expect(lines[2]).toBe('LUT_3D_SIZE 2')
    expect(lines[3]).toBe('DOMAIN_MIN 0.000000 0.000000 0.000000')
    expect(lines[4]).toBe('DOMAIN_MAX 1.000000 1.000000 1.000000')
    expect(lines[5]).toBe('0.000000 0.000000 0.000000')
    expect(lines[6]).toBe('1.000000 0.000000 0.000000')
    expect(lines[7]).toBe('0.000000 1.000000 0.000000')
    expect(lines[8]).toBe('1.000000 1.000000 0.000000')
    expect(lines[9]).toBe('0.000000 0.000000 1.000000')
    expect(lines).toHaveLength(5 + 8)
  })
})
